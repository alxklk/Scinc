# The 6x12 glyphs for tvgfx.h's small raster mode, imported by genrfont.py.
# ground/font6x12.h has ASCII and the IBM PC box characters; everything else is
# composed from its letters or drawn here (rows of 6, '*' set, from the given row).
import re,unicodedata

def load(path):
    s=open(path).read()
    s=s[s.index('font6x12Data[]={'):]
    rows=re.findall(r'BIN8\("([^"]*)"\)',s)
    return {32+i:[r.ljust(6)[:6] for r in rows[i*12:(i+1)*12]] for i in range(len(rows)//12)}

def A(top,art):
    out=[' '*6]*12
    for i,l in enumerate(art.split('/')):
        out[top+i]=l.ljust(6,'.')[:6].replace('.',' ')
    return out

def over(base,top,art):
    g=[list(r) for r in base]
    for i,l in enumerate(art.split('/')):
        for j,ch in enumerate(l):
            if ch=='*': g[top+i][j]='*'
    return ["".join(r) for r in g]

def clear(base,rows):
    return [(' '*6 if i in rows else r) for i,r in enumerate(base)]

